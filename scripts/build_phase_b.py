"""Download the phase B ENTSO-E data, build the standard frames and write the data report.

Needs ENTSOE_API_KEY. Raw series are cached as parquet in data/cache/ (git-ignored, never
committed); the standard frame (Belgian price, French generation and load forecasts) is
written there too.
Outputs: results/data_report.md and results/data_report.json (merged into
results/metrics.json under "data_report").

Usage: python scripts/build_phase_b.py
"""

from __future__ import annotations

import json

import pandas as pd

from be_power_forecast.config import CACHE_DIR, RESULTS_DIR
from be_power_forecast.data.calendar import to_local_days
from be_power_forecast.data.sources import EntsoeSource


def series_report(name: str, raw: pd.Series) -> dict:
    days, rep = to_local_days(raw)
    step = raw.index.to_series().diff()
    local_day = raw.index.tz_convert("Europe/Brussels").tz_localize(None).normalize()
    quarter_days = local_day[(step == pd.Timedelta("15min")).to_numpy()].unique()
    dropped = pd.DatetimeIndex(rep["dropped_days"])
    per_year = {}
    for year, block in days.groupby(days.index.year):
        per_year[int(year)] = {
            "days": len(block),
            "complete_days": int(block.notna().all(axis=1).sum()),
            "dropped_days": int((dropped.year == year).sum()),
            "quarter_hour_days": int((quarter_days.year == year).sum()),
        }
    return {
        "first": str(raw.index.min()),
        "last": str(raw.index.max()),
        "raw_values": len(raw),
        "raw_missing_values": int(raw.isna().sum()),
        "dst_23h_days": rep["dst_23h_days"],
        "dst_25h_days": rep["dst_25h_days"],
        "interpolated_hours": rep["interpolated_hours"],
        "dropped_days": rep["dropped_days"],
        "per_year": per_year,
    }


def price_stats(frame: pd.DataFrame) -> dict:
    price = frame["Price"].dropna()
    out = {}
    for year, p in price.groupby(price.index.year):
        out[int(year)] = {
            "hours": len(p),
            "mean": float(p.mean()),
            "min": float(p.min()),
            "max": float(p.max()),
            "share_negative_pct": float(100 * (p < 0).mean()),
        }
    return out


def to_markdown(report: dict) -> str:
    md = ["# Phase B data report", "", "Generated by `scripts/build_phase_b.py`.", ""]
    md += ["## Coverage per series", ""]
    md += [
        "| Series | First | Last | DST 23 h | DST 25 h | Interpolated hours | Dropped days |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r in report["series"].items():
        md.append(
            f"| {name} | {r['first'][:16]} | {r['last'][:16]} | {r['dst_23h_days']} | "
            f"{r['dst_25h_days']} | {len(r['interpolated_hours'])} | {len(r['dropped_days'])} |"
        )
    md += ["", "## Per series and year (complete days / days, dropped, quarter-hour days)", ""]
    years = sorted({y for r in report["series"].values() for y in r["per_year"]})
    md += ["| Series | " + " | ".join(map(str, years)) + " |", "|---" * (len(years) + 1) + "|"]
    for name, r in report["series"].items():
        cells = []
        for y in years:
            c = r["per_year"].get(y)
            cells.append(
                f"{c['complete_days']}/{c['days']}, {c['dropped_days']}, {c['quarter_hour_days']}"
                if c
                else "—"
            )
        md.append(f"| {name} | " + " | ".join(cells) + " |")
    md += ["", "## Interpolated hours (isolated missing hour, local time)", ""]
    for name, r in report["series"].items():
        md.append(f"- {name}: {', '.join(r['interpolated_hours']) or 'none'}")
    md += ["", "## Dropped days (gap longer than one hour, never filled)", ""]
    for name, r in report["series"].items():
        md.append(f"- {name}: {', '.join(r['dropped_days']) or 'none'}")
    f = report["frame"]
    md += ["", "## Standard frame", ""]
    md.append(
        f"{f['first_day']} to {f['last_day']}: {f['days']} days, "
        f"{len(f['dropped_days'])} dropped (any series): {', '.join(f['dropped_days']) or 'none'}."
    )
    md += ["", "## Belgian day-ahead price per year (EUR/MWh, hourly values)", ""]
    md += ["| Year | Hours | Mean | Min | Max | Negative % |", "|---|---|---|---|---|---|"]
    for y, s in report["price"].items():
        md.append(
            f"| {y} | {s['hours']} | {s['mean']:.2f} | {s['min']:.2f} | {s['max']:.2f} | "
            f"{s['share_negative_pct']:.2f} |"
        )
    return "\n".join(md) + "\n"


def main() -> None:
    source = EntsoeSource()
    raw = {name: source.raw(name) for name in source.columns}
    frame = source.load()
    frame.to_parquet(CACHE_DIR / "phase_b_FR.parquet")
    report = {
        "series": {n: series_report(n, s) for n, s in raw.items()},
        "frame": {
            "first_day": str(frame.index[0].date()),
            "last_day": str(frame.index[-1].date()),
            "days": len(frame) // 24,
            "dropped_days": source.report["dropped_days_any_series"],
        },
        "price": price_stats(frame),
    }
    (RESULTS_DIR / "data_report.json").write_text(json.dumps(report, indent=1))
    (RESULTS_DIR / "data_report.md").write_text(to_markdown(report))
    metrics_path = RESULTS_DIR / "metrics.json"
    metrics = json.loads(metrics_path.read_text())
    metrics["data_report"] = report
    metrics_path.write_text(json.dumps(metrics, indent=1))
    print(to_markdown(report))


if __name__ == "__main__":
    main()
