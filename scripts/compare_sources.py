"""Compare the benchmark dataset (BE.csv, Lago et al., 2021) with ENTSO-E on their common hours.

Both sources cover 2015-2016 (ENTSO-E data start in January 2015, BE.csv ends on
2016-12-31). The comparison is descriptive: the join itself is set in config.py.

Reads the ENTSO-E cache written by scripts/build_phase_b.py (data/cache/, git-ignored).
Outputs: results/source_comparison.md, results/figures/source_comparison.png and
results/source_comparison.json (merged into results/metrics.json by make_report.py under
"source_comparison").

Usage: python scripts/compare_sources.py
"""

from __future__ import annotations

import json

import matplotlib.pyplot as plt
import pandas as pd

from be_power_forecast.config import RESULTS_DIR, TZ
from be_power_forecast.data.compare import compare, largest_daily_gaps, local_hourly, monthly
from be_power_forecast.data.sources import EntsoeSource, LagoZenodoSource

OVERLAP = ("2015-01-01", "2016-12-31")
UNITS = {"Price": "EUR/MWh", "Generation forecast FR": "MW", "Load forecast FR": "MW"}
BLUE, ORANGE, GREY, INK = "#2a78d6", "#eb6834", "#8a8984", "#52514e"


def level_shift(reference: pd.Series, other: pd.Series, half: int = 28) -> dict:
    """Day with the largest change of mean daily bias between the ``half`` days before and
    after it (no threshold), and the agreement statistics on each side."""
    diff = (reference - other).dropna()
    daily = diff.groupby(diff.index.normalize()).mean()
    after = daily.rolling(half).mean().shift(-(half - 1))
    before = daily.rolling(half).mean().shift(1)
    jump = (after - before).abs()
    day = jump.idxmax()
    cut = day - pd.Timedelta(hours=1)
    return {
        "day": str(day.date()),
        "jump": float(jump.max()),
        "before": compare(reference.loc[:cut], other.loc[:cut]),
        "after": compare(reference.loc[day:], other.loc[day:]),
    }


def generation_to_load(gen: pd.Series, load: pd.Series) -> dict:
    """Yearly mean ratio of generation to load forecasts (France is a net exporter)."""
    ratio = (gen / load).dropna()
    return {int(y): float(r.mean()) for y, r in ratio.groupby(ratio.index.year)}


def figure(months: dict, path) -> None:
    fig, axes = plt.subplots(1, 2, figsize=(9, 3.4), dpi=150, sharey=True)
    for ax, name in zip(axes, ["Generation forecast FR", "Load forecast FR"], strict=True):
        m = months[name]
        x = m.index.to_timestamp()
        for side in ("top", "right"):
            ax.spines[side].set_visible(False)
        ax.spines["left"].set_color(GREY)
        ax.spines["bottom"].set_color(GREY)
        ax.tick_params(colors=INK, labelsize=8)
        ax.grid(axis="y", color="#e4e3df", linewidth=0.8)
        ax.set_axisbelow(True)
        ax.axhline(0, color=GREY, lw=0.8)
        ax.plot(x, m["bias"] / 1000, color=BLUE, lw=2, marker="o", ms=3, label="Mean difference")
        ax.plot(x, m["mae"] / 1000, color=ORANGE, lw=2, label="Mean absolute difference")
        ax.set_title(name, color=INK, fontsize=9)
    axes[0].set_ylabel("BE.csv - ENTSO-E, monthly (GW)", color=INK, fontsize=8)
    axes[1].legend(frameon=False, fontsize=7)
    fig.suptitle("BE.csv vs ENTSO-E on their common hours (2015-2016)", color=INK, fontsize=10)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def to_markdown(rep: dict, months: dict) -> str:
    md = ["# Source comparison: BE.csv vs ENTSO-E (2015-2016)", ""]
    md += [
        "Generated by `scripts/compare_sources.py`. Difference = BE.csv - ENTSO-E, on the "
        "local Brussels hours present in both sources (ENTSO-E days built by "
        "`data/calendar.py`)."
    ]
    md += ["", "## Overall agreement", ""]
    md += [
        "| Series | Unit | Hours | Equal % | Bias | MAE | MAE % of mean | Max abs | Corr | "
        "Best shift (h) |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    for name, r in rep["series"].items():
        a = r["all"]
        md.append(
            f"| {name} | {UNITS[name]} | {a['hours']} | {a['share_equal_pct']:.2f} | "
            f"{a['bias']:.2f} | {a['mae']:.2f} | {a['mae_pct_of_mean']:.2f} | "
            f"{a['max_abs']:.2f} | {a['corr']:.4f} | {a['best_shift_hours']} |"
        )
    md += ["", "## Per year", ""]
    md += ["| Series | Year | Bias | MAE | MAE % of mean | Corr |", "|---|---|---|---|---|---|"]
    for name, r in rep["series"].items():
        for y, a in r["per_year"].items():
            md.append(
                f"| {name} | {y} | {a['bias']:.2f} | {a['mae']:.2f} | "
                f"{a['mae_pct_of_mean']:.2f} | {a['corr']:.4f} |"
            )
    md += ["", "## Largest level shift of the daily mean difference (28 days each side)", ""]
    md += [
        "| Series | Day | Jump | Bias before | MAE % before | Bias after | MAE % after |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, r in rep["series"].items():
        s = r["level_shift"]
        md.append(
            f"| {name} | {s['day']} | {s['jump']:.2f} | {s['before']['bias']:.2f} | "
            f"{s['before']['mae_pct_of_mean']:.2f} | {s['after']['bias']:.2f} | "
            f"{s['after']['mae_pct_of_mean']:.2f} |"
        )
    md += ["", "## Mean ratio generation / load forecast for France, per year", ""]
    g = rep["generation_to_load"]
    years = sorted(set(g["BE.csv"]) | set(g["ENTSO-E"]))
    md += ["| Source | " + " | ".join(map(str, years)) + " |", "|---" * (len(years) + 1) + "|"]
    for src, vals in g.items():
        cells = [f"{vals[y]:.3f}" if y in vals else "—" for y in years]
        md.append(f"| {src} | " + " | ".join(cells) + " |")
    md += ["", "## Monthly mean difference", ""]
    for name, m in months.items():
        md += [f"### {name} ({UNITS[name]})", ""]
        md += ["| Month | BE.csv | ENTSO-E | Bias | MAE | Corr |", "|---|---|---|---|---|---|"]
        for p, row in m.iterrows():
            md.append(
                f"| {p} | {row['reference']:.2f} | {row['other']:.2f} | {row['bias']:.2f} | "
                f"{row['mae']:.2f} | {row['corr']:.4f} |"
            )
        md.append("")
    md += ["## Days with the largest hourly difference", ""]
    for name, r in rep["series"].items():
        days = ", ".join(f"{d} ({v:.2f})" for d, v in r["largest_days"].items())
        md.append(f"- {name}: {days}")
    md += ["", "## ENTSO-E days not built (gap longer than one hour)", ""]
    for name, r in rep["series"].items():
        md.append(f"- {name}: {', '.join(r['entsoe_dropped_days']) or 'none'}")
    return "\n".join(md) + "\n"


def main() -> None:
    csv = LagoZenodoSource().load()
    entsoe = EntsoeSource()  # phase B download window, read from the cache
    # Same bounds as a download of the overlap only: local Brussels days, end day included.
    lo = pd.Timestamp(OVERLAP[0], tz=TZ)
    hi = pd.Timestamp(OVERLAP[1], tz=TZ) + pd.Timedelta(days=1)
    rep: dict = {"overlap": list(OVERLAP), "series": {}}
    months, hourly = {}, {}
    for name in entsoe.columns:
        raw = entsoe.raw(name)
        raw = raw[(raw.index >= lo) & (raw.index < hi)]
        other, day_report = local_hourly(raw)
        ref = csv[name].loc[OVERLAP[0] :]
        hourly[name] = other
        months[name] = monthly(ref, other)
        rep["series"][name] = {
            "all": compare(ref, other),
            "per_year": {
                int(y): compare(ref.loc[str(y)], other.loc[str(y)])
                for y in sorted(set(ref.index.year))
            },
            "level_shift": level_shift(ref, other),
            "largest_days": {
                str(d.date()): float(v) for d, v in largest_daily_gaps(ref, other).items()
            },
            "entsoe_dropped_days": day_report["dropped_days"],
        }
    rep["generation_to_load"] = {
        "BE.csv": generation_to_load(csv["Generation forecast FR"], csv["Load forecast FR"]),
        "ENTSO-E": generation_to_load(hourly["Generation forecast FR"], hourly["Load forecast FR"]),
    }
    fig_path = RESULTS_DIR / "figures" / "source_comparison.png"
    figure(months, fig_path)
    md = to_markdown(rep, months)
    (RESULTS_DIR / "source_comparison.md").write_text(md)
    (RESULTS_DIR / "source_comparison.json").write_text(json.dumps(rep, indent=1))
    print(md)


if __name__ == "__main__":
    main()
